create or replace function public.add_product_to_cart(p_product_id integer)
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  saved_quantity integer;
begin
  if auth.uid() is null then
    raise exception 'Sign in before saving a shopping bag';
  end if;

  insert into public.cart_items (user_id, product_id, quantity)
  values (auth.uid(), p_product_id, 1)
  on conflict (user_id, product_id)
  do update set quantity = least(public.cart_items.quantity + 1, 99)
  returning quantity into saved_quantity;

  return saved_quantity;
end;
$$;

grant execute on function public.add_product_to_cart(integer) to authenticated;

create or replace function public.consume_newsletter_rate_limit(
  p_ip_hash text,
  p_now timestamptz,
  p_max_requests integer default 3,
  p_window_seconds integer default 3600
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_window public.newsletter_rate_limits%rowtype;
begin
  if p_ip_hash is null or length(p_ip_hash) < 32 or p_max_requests < 1 or p_window_seconds < 1 then
    raise exception 'Invalid newsletter rate limit parameters';
  end if;

  delete from public.newsletter_rate_limits
    where window_started_at < p_now - interval '1 day';

  insert into public.newsletter_rate_limits (ip_hash, window_started_at, request_count)
  values (p_ip_hash, p_now, 1)
  on conflict (ip_hash) do nothing;

  select *
    into current_window
    from public.newsletter_rate_limits
    where ip_hash = p_ip_hash
    for update;

  if current_window.window_started_at <= p_now - make_interval(secs => p_window_seconds) then
    update public.newsletter_rate_limits
      set window_started_at = p_now, request_count = 1
      where ip_hash = p_ip_hash;
    return true;
  end if;

  if current_window.request_count >= p_max_requests then
    return false;
  end if;

  update public.newsletter_rate_limits
    set request_count = request_count + 1
    where ip_hash = p_ip_hash;
  return true;
end;
$$;

revoke all on function public.consume_newsletter_rate_limit(text, timestamptz, integer, integer) from public, anon, authenticated;
grant execute on function public.consume_newsletter_rate_limit(text, timestamptz, integer, integer) to service_role;

create or replace function public.place_cod_order(
  p_shipping_name text,
  p_phone text,
  p_address_line text,
  p_city text,
  p_postal_code text default ''
)
returns table (order_id uuid, total_paisa bigint)
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_order_id uuid;
  current_user_id uuid := auth.uid();
  item_total bigint;
begin
  if current_user_id is null then
    raise exception 'Sign in before placing an order';
  end if;
  if nullif(trim(p_shipping_name), '') is null or length(trim(p_shipping_name)) > 120 then
    raise exception 'Enter a valid full name';
  end if;
  if nullif(trim(p_phone), '') is null or length(trim(p_phone)) > 40 then
    raise exception 'Enter a valid phone number';
  end if;
  if nullif(trim(p_address_line), '') is null or length(trim(p_address_line)) > 300 then
    raise exception 'Enter a valid delivery address';
  end if;
  if nullif(trim(p_city), '') is null or length(trim(p_city)) > 120 then
    raise exception 'Enter a valid city';
  end if;
  if length(coalesce(p_postal_code, '')) > 20 then
    raise exception 'Enter a valid postal code';
  end if;

  perform 1
    from public.cart_items
    where user_id = current_user_id
    for update;

  if not found then
    raise exception 'Your shopping bag is empty';
  end if;

  if exists (
    select 1
    from public.cart_items as cart
    left join public.products as product
      on product.id = cart.product_id and product.is_active
    where cart.user_id = current_user_id and product.id is null
  ) then
    raise exception 'A piece in your bag is no longer available. Refresh your bag and try again.';
  end if;

  select sum(product.price_paisa * cart.quantity)
    into item_total
    from public.cart_items as cart
    join public.products as product on product.id = cart.product_id
    where cart.user_id = current_user_id and product.is_active;

  if item_total is null or item_total <= 0 then
    raise exception 'Your shopping bag has no available pieces';
  end if;

  insert into public.orders (
    user_id, total_paisa, shipping_name, phone, address_line, city, postal_code
  ) values (
    current_user_id, item_total, trim(p_shipping_name), trim(p_phone),
    trim(p_address_line), trim(p_city), trim(coalesce(p_postal_code, ''))
  )
  returning id into new_order_id;

  insert into public.order_items (order_id, product_id, product_name, image_path, quantity, unit_price_paisa)
    select new_order_id, product.id, product.name, product.image_path, cart.quantity, product.price_paisa
    from public.cart_items as cart
    join public.products as product on product.id = cart.product_id
    where cart.user_id = current_user_id and product.is_active;

  delete from public.cart_items where user_id = current_user_id;

  return query select new_order_id, item_total;
end;
$$;

revoke all on function public.place_cod_order(text, text, text, text, text) from public, anon;
grant execute on function public.place_cod_order(text, text, text, text, text) to authenticated;
