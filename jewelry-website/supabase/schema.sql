create table if not exists public.products (
  id integer generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('Rings', 'Necklaces', 'Earrings', 'Bracelets')),
  price_paisa bigint not null check (price_paisa >= 0),
  image_path text not null,
  image_alt text not null default '',
  badge text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.cart_items (
  user_id uuid not null references auth.users (id) on delete cascade,
  product_id integer not null references public.products (id) on delete cascade,
  quantity integer not null default 1 check (quantity between 1 and 99),
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create table if not exists public.wishlist_items (
  user_id uuid not null references auth.users (id) on delete cascade,
  product_id integer not null references public.products (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  status text not null default 'confirmed' check (status in ('confirmed', 'processing', 'shipped', 'delivered', 'cancelled')),
  payment_method text not null default 'cod' check (payment_method = 'cod'),
  payment_status text not null default 'pending' check (payment_status in ('pending', 'paid', 'cancelled')),
  total_paisa bigint not null check (total_paisa >= 0),
  shipping_name text not null,
  phone text not null,
  address_line text not null,
  city text not null,
  postal_code text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  product_id integer references public.products (id) on delete set null,
  product_name text not null,
  image_path text not null,
  quantity integer not null check (quantity between 1 and 99),
  unit_price_paisa bigint not null check (unit_price_paisa >= 0)
);

create table if not exists public.newsletter_subscriptions (
  id bigint generated always as identity primary key,
  email text not null unique check (email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'),
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'unsubscribed')),
  confirmation_token_hash text,
  confirmation_expires_at timestamptz,
  last_confirmation_sent_at timestamptz,
  consented_at timestamptz not null default now(),
  confirmed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.newsletter_rate_limits (
  ip_hash text primary key,
  window_started_at timestamptz not null,
  request_count integer not null default 1 check (request_count > 0)
);

revoke all on public.newsletter_subscriptions, public.newsletter_rate_limits from anon, authenticated;

